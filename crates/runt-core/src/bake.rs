/// One resident baked texture: both maps, their sampling params, and the bind
/// group `@group(2)` of the material shader wants.
pub struct GpuTexture {
    pub albedo: wgpu::Texture,
    pub normal: wgpu::Texture,
    pub params: wgpu::Buffer,
    pub bind_group: wgpu::BindGroup,
}

/// Handle → GPU textures. The texture-side twin of
/// [`MeshRegistry`](crate::registry::MeshRegistry), and content-addressed for
/// the same reason: two materials naming the same spec share one bake.
pub struct TextureRegistry {
    textures: HashMap<TextureHandle, GpuTexture>,
    layout: wgpu::BindGroupLayout,
    sampler: wgpu::Sampler,
    /// What an entity with no texture binds. `@group(2)` is in the pipeline
    /// layout unconditionally — one layout for every variant is simpler than
    /// two and costs an untextured draw one bind-group set that the sort order
    /// already makes near-free — so *something* legal has to be there.
    default_bind_group: wgpu::BindGroup,
    /// Kept alive explicitly rather than relying on the bind group's internal
    /// references: a 1×1 texture costs nothing and an owner that reads as an
    /// owner costs nothing either.
    _default_resources: (wgpu::Texture, wgpu::Texture, wgpu::Buffer),
}

impl TextureRegistry {
    pub fn new(device: &wgpu::Device, queue: &wgpu::Queue) -> TextureRegistry {
        let layout = device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {
            label: Some("texture bind layout"),
            entries: &[
                wgpu::BindGroupLayoutEntry {
                    binding: 0,
                    visibility: wgpu::ShaderStages::FRAGMENT,
                    ty: wgpu::BindingType::Texture {
                        sample_type: wgpu::TextureSampleType::Float { filterable: true },
                        view_dimension: wgpu::TextureViewDimension::D2,
                        multisampled: false,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 1,
                    visibility: wgpu::ShaderStages::FRAGMENT,
                    ty: wgpu::BindingType::Texture {
                        sample_type: wgpu::TextureSampleType::Float { filterable: true },
                        view_dimension: wgpu::TextureViewDimension::D2,
                        multisampled: false,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 2,
                    visibility: wgpu::ShaderStages::FRAGMENT,
                    ty: wgpu::BindingType::Sampler(wgpu::SamplerBindingType::Filtering),
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 3,
                    visibility: wgpu::ShaderStages::FRAGMENT,
                    ty: wgpu::BindingType::Buffer {
                        ty: wgpu::BufferBindingType::Uniform,
                        has_dynamic_offset: false,
                        min_binding_size: wgpu::BufferSize::new(16),
                    },
                    count: None,
                },
            ],
        });

        // Repeat, because the bake *is* a tile — a clamped sampler would smear
        // the last texel across a hillside.
        let sampler = device.create_sampler(&wgpu::SamplerDescriptor {
            label: Some("baked texture sampler"),
            address_mode_u: wgpu::AddressMode::Repeat,
            address_mode_v: wgpu::AddressMode::Repeat,
            address_mode_w: wgpu::AddressMode::Repeat,
            mag_filter: wgpu::FilterMode::Linear,
            min_filter: wgpu::FilterMode::Linear,
            mipmap_filter: wgpu::MipmapFilterMode::Nearest,
            ..Default::default()
        });

        // 1×1 white albedo and 1×1 flat normal: an untextured material's
        // sampling multiplies by white and perturbs the normal by nothing, so
        // the bit-unset path is *provably* the pre-texture look.
        let white = upload_target(device, queue, 1, &[255, 255, 255, 255], "default albedo");
        let flat = upload_target(device, queue, 1, &[128, 128, 255, 255], "default normal");
        let default_params = create_params(device, queue, 1.0, 4.0, false);
        let default_bind_group = create_bind_group(
            device,
            &layout,
            &sampler,
            &white,
            &flat,
            &default_params,
            "default texture bind group",
        );

        TextureRegistry {
            textures: HashMap::new(),
            layout,
            sampler,
            default_bind_group,
            _default_resources: (white, flat, default_params),
        }
    }

    /// The `@group(2)` layout the render pipelines are built against.
    pub fn layout(&self) -> &wgpu::BindGroupLayout {
        &self.layout
    }

    /// What an untextured draw binds.
    pub fn default_bind_group(&self) -> &wgpu::BindGroup {
        &self.default_bind_group
    }

    pub fn get(&self, handle: TextureHandle) -> Option<&GpuTexture> {
        self.textures.get(&handle)
    }

    pub fn contains(&self, handle: TextureHandle) -> bool {
        self.textures.contains_key(&handle)
    }

    pub fn len(&self) -> usize {
        self.textures.len()
    }

    pub fn is_empty(&self) -> bool {
        self.textures.is_empty()
    }

    /// Resolve `spec` at `resolution` to a resident texture, in this order:
    ///
    /// 1. **Memory.** Already baked this session → nothing happens.
    /// 2. **Store.** A validated entry → upload its pixels, no bake.
    /// 3. **Cold.** Run the bake pass, and write the pixels back if the store
    ///    can hold them.
    ///
    /// Every path returns the same handle and the same pixels, so a caller
    /// cannot tell which one ran.
    pub fn resolve(
        &mut self,
        device: &wgpu::Device,
        queue: &wgpu::Queue,
        baker: &TextureBaker,
        spec: &TextureSpec,
        resolution: u32,
        store: &dyn CacheStore,
    ) -> TextureHandle {
        let handle = TextureHandle(spec.content_key(resolution));
        if self.textures.contains_key(&handle) {
            return handle;
        }

        let (albedo, normal) = match store.load_texture(handle.0) {
            Some(data) if data.matches(spec, resolution) => (
                upload_target(device, queue, resolution, &data.albedo, "cached albedo"),
                upload_target(device, queue, resolution, &data.normal, "cached normal"),
            ),
            other => {
                if other.is_some() {
                    log::warn!(
                        "runt-cache: texture {:#018x} does not match the spec it is filed \
                         under; discarding and rebaking",
                        handle.0
                    );
                }
                let (albedo, normal) = baker.bake(device, queue, spec, resolution);
                if store.caches_textures() {
                    if let (Some(a), Some(n)) = (
                        read_target(device, queue, &albedo, resolution),
                        read_target(device, queue, &normal, resolution),
                    ) {
                        store.store_texture(
                            handle.0,
                            &TextureData {
                                resolution,
                                spec: postcard::to_stdvec(spec).unwrap_or_default(),
                                albedo: a,
                                normal: n,
                            },
                        );
                    }
                }
                (albedo, normal)
            }
        };

        let params = create_params(
            device,
            queue,
            spec.world_scale,
            spec.triplanar_sharpness,
            spec.anti_tiling,
        );
        let bind_group = create_bind_group(
            device,
            &self.layout,
            &self.sampler,
            &albedo,
            &normal,
            &params,
            "baked texture bind group",
        );
        self.textures.insert(
            handle,
            GpuTexture {
                albedo,
                normal,
                params,
                bind_group,
            },
        );
        handle
    }
}

/// The per-texture sampling params: `(world_scale, sharpness, anti-tiling, 0)`.
///
/// They live with the *texture*, not the instance, because they describe how
/// this bake maps onto the world — two entities wearing the same grass want the
/// same tiling whether or not anyone remembered to copy a number.
fn create_params(
    device: &wgpu::Device,
    queue: &wgpu::Queue,
    world_scale: f32,
    sharpness: f32,
    anti_tiling: bool,
) -> wgpu::Buffer {
    let buffer = device.create_buffer(&wgpu::BufferDescriptor {
        label: Some("texture params"),
        size: 16,
        usage: wgpu::BufferUsages::UNIFORM | wgpu::BufferUsages::COPY_DST,
        mapped_at_creation: false,
    });
    let values: [f32; 4] = [
        world_scale,
        sharpness,
        if anti_tiling { 1.0 } else { 0.0 },
        0.0,
    ];
    queue.write_buffer(&buffer, 0, bytemuck::bytes_of(&values));
    buffer
}

fn create_bind_group(
    device: &wgpu::Device,
    layout: &wgpu::BindGroupLayout,
    sampler: &wgpu::Sampler,
    albedo: &wgpu::Texture,
    normal: &wgpu::Texture,
    params: &wgpu::Buffer,
    label: &str,
) -> wgpu::BindGroup {
    let albedo_view = albedo.create_view(&wgpu::TextureViewDescriptor::default());
    let normal_view = normal.create_view(&wgpu::TextureViewDescriptor::default());
    device.create_bind_group(&wgpu::BindGroupDescriptor {
        label: Some(label),
        layout,
        entries: &[
            wgpu::BindGroupEntry {
                binding: 0,
                resource: wgpu::BindingResource::TextureView(&albedo_view),
            },
            wgpu::BindGroupEntry {
                binding: 1,
                resource: wgpu::BindingResource::TextureView(&normal_view),
            },
            wgpu::BindGroupEntry {
                binding: 2,
                resource: wgpu::BindingResource::Sampler(sampler),
            },
            wgpu::BindGroupEntry {
                binding: 3,
                resource: params.as_entire_binding(),
            },
        ],
    })
}
