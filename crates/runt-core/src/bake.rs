/// The bake pass's pipelines and its one uniform slot.
///
/// Built once per [`Renderer`](crate::Renderer). Bakes run one at a time and
/// each submits before the next writes the uniform, so a single buffer is
/// enough — there is no frame pipelining to race with.
pub struct TextureBaker {
    albedo: wgpu::RenderPipeline,
    normal: wgpu::RenderPipeline,
    buffer: wgpu::Buffer,
    bind_group: wgpu::BindGroup,
}

impl TextureBaker {
    pub fn new(device: &wgpu::Device) -> TextureBaker {
        let layout = device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {
            label: Some("bake params layout"),
            entries: &[wgpu::BindGroupLayoutEntry {
                binding: 0,
                visibility: wgpu::ShaderStages::FRAGMENT,
                ty: wgpu::BindingType::Buffer {
                    ty: wgpu::BufferBindingType::Uniform,
                    has_dynamic_offset: false,
                    min_binding_size: wgpu::BufferSize::new(
                        std::mem::size_of::<BakeUniform>() as u64
                    ),
                },
                count: None,
            }],
        });
        let buffer = device.create_buffer(&wgpu::BufferDescriptor {
            label: Some("bake params"),
            size: std::mem::size_of::<BakeUniform>() as u64,
            usage: wgpu::BufferUsages::UNIFORM | wgpu::BufferUsages::COPY_DST,
            mapped_at_creation: false,
        });
        let bind_group = device.create_bind_group(&wgpu::BindGroupDescriptor {
            label: Some("bake params bind group"),
            layout: &layout,
            entries: &[wgpu::BindGroupEntry {
                binding: 0,
                resource: buffer.as_entire_binding(),
            }],
        });

        let pipeline_layout = device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {
            label: Some("bake pipeline layout"),
            bind_group_layouts: &[Some(&layout)],
            immediate_size: 0,
        });
        let shader = device.create_shader_module(wgpu::ShaderModuleDescriptor {
            label: Some("texture bake"),
            source: wgpu::ShaderSource::Wgsl(bake_shader_source().into()),
        });

        let make = |entry: &str, label: &str| {
            device.create_render_pipeline(&wgpu::RenderPipelineDescriptor {
                label: Some(label),
                layout: Some(&pipeline_layout),
                vertex: wgpu::VertexState {
                    module: &shader,
                    entry_point: Some("vs_bake"),
                    buffers: &[],
                    compilation_options: Default::default(),
                },
                fragment: Some(wgpu::FragmentState {
                    module: &shader,
                    entry_point: Some(entry),
                    targets: &[Some(wgpu::ColorTargetState {
                        format: BAKE_FORMAT,
                        blend: Some(wgpu::BlendState::REPLACE),
                        write_mask: wgpu::ColorWrites::ALL,
                    })],
                    compilation_options: Default::default(),
                }),
                primitive: wgpu::PrimitiveState {
                    topology: wgpu::PrimitiveTopology::TriangleList,
                    cull_mode: None,
                    ..Default::default()
                },
                depth_stencil: None,
                multisample: wgpu::MultisampleState::default(),
                multiview_mask: None,
                cache: None,
            })
        };

        TextureBaker {
            albedo: make("fs_albedo", "bake albedo"),
            normal: make("fs_normal", "bake normal"),
            buffer,
            bind_group,
        }
    }

    /// Render `spec` to a fresh (albedo, normal) pair at `resolution`.
    pub fn bake(
        &self,
        device: &wgpu::Device,
        queue: &wgpu::Queue,
        spec: &TextureSpec,
        resolution: u32,
    ) -> (wgpu::Texture, wgpu::Texture) {
        queue.write_buffer(
            &self.buffer,
            0,
            bytemuck::bytes_of(&BakeUniform::from_spec(spec)),
        );

        let albedo = create_target(device, resolution, "baked albedo");
        let normal = create_target(device, resolution, "baked normal");

        let mut encoder =
            device.create_command_encoder(&wgpu::CommandEncoderDescriptor { label: Some("bake") });
        for (texture, pipeline, label) in [
            (&albedo, &self.albedo, "bake albedo pass"),
            (&normal, &self.normal, "bake normal pass"),
        ] {
            let view = texture.create_view(&wgpu::TextureViewDescriptor::default());
            let mut pass = encoder.begin_render_pass(&wgpu::RenderPassDescriptor {
                label: Some(label),
                color_attachments: &[Some(wgpu::RenderPassColorAttachment {
                    view: &view,
                    resolve_target: None,
                    ops: wgpu::Operations {
                        // The fullscreen triangle covers every texel, so the
                        // clear only exists to keep the attachment defined.
                        load: wgpu::LoadOp::Clear(wgpu::Color::BLACK),
                        store: wgpu::StoreOp::Store,
                    },
                    depth_slice: None,
                })],
                depth_stencil_attachment: None,
                timestamp_writes: None,
                occlusion_query_set: None,
                multiview_mask: None,
            });
            pass.set_pipeline(pipeline);
            pass.set_bind_group(0, &self.bind_group, &[]);
            pass.draw(0..3, 0..1);
        }
        queue.submit(Some(encoder.finish()));

        (albedo, normal)
    }
}

fn create_target(device: &wgpu::Device, resolution: u32, label: &str) -> wgpu::Texture {
    device.create_texture(&wgpu::TextureDescriptor {
        label: Some(label),
        size: wgpu::Extent3d {
            width: resolution,
            height: resolution,
            depth_or_array_layers: 1,
        },
        // One level. Mipmaps would want a downsample chain and the anti-tiling
        // sampler would want `textureSampleGrad` to keep them correct; both are
        // future work, and the material samples at an explicit LOD 0 so nothing
        // silently reads a level that is not there.
        mip_level_count: 1,
        sample_count: 1,
        dimension: wgpu::TextureDimension::D2,
        format: BAKE_FORMAT,
        usage: wgpu::TextureUsages::RENDER_ATTACHMENT
            | wgpu::TextureUsages::TEXTURE_BINDING
            | wgpu::TextureUsages::COPY_SRC
            | wgpu::TextureUsages::COPY_DST,
        view_formats: &[],
    })
}

/// Upload already-baked pixels — the cache-hit path, which must land on exactly
/// the texture a cold bake would have produced.
pub fn upload_target(
    device: &wgpu::Device,
    queue: &wgpu::Queue,
    resolution: u32,
    pixels: &[u8],
    label: &str,
) -> wgpu::Texture {
    let texture = create_target(device, resolution, label);
    queue.write_texture(
        texture.as_image_copy(),
        pixels,
        wgpu::TexelCopyBufferLayout {
            offset: 0,
            bytes_per_row: Some(resolution * 4),
            rows_per_image: Some(resolution),
        },
        wgpu::Extent3d {
            width: resolution,
            height: resolution,
            depth_or_array_layers: 1,
        },
    );
    texture
}

/// Read an RGBA8 texture back, tightly packed.
///
/// Blocking: it polls the device until the map callback fires. Only ever called
/// when a [`CacheStore`] said it can persist textures, which the web store does
/// not (there is no blocking poll in a browser).
pub fn read_target(
    device: &wgpu::Device,
    queue: &wgpu::Queue,
    texture: &wgpu::Texture,
    resolution: u32,
) -> Option<Vec<u8>> {
    let unpadded = resolution * 4;
    // `copy_texture_to_buffer` wants rows aligned to 256 bytes.
    let padded = unpadded.div_ceil(256) * 256;
    let readback = device.create_buffer(&wgpu::BufferDescriptor {
        label: Some("bake readback"),
        size: (padded as u64) * (resolution as u64),
        usage: wgpu::BufferUsages::COPY_DST | wgpu::BufferUsages::MAP_READ,
        mapped_at_creation: false,
    });

    let mut encoder = device.create_command_encoder(&wgpu::CommandEncoderDescriptor {
        label: Some("bake readback"),
    });
    encoder.copy_texture_to_buffer(
        texture.as_image_copy(),
        wgpu::TexelCopyBufferInfo {
            buffer: &readback,
            layout: wgpu::TexelCopyBufferLayout {
                offset: 0,
                bytes_per_row: Some(padded),
                rows_per_image: Some(resolution),
            },
        },
        wgpu::Extent3d {
            width: resolution,
            height: resolution,
            depth_or_array_layers: 1,
        },
    );
    queue.submit(Some(encoder.finish()));

    let (tx, rx) = std::sync::mpsc::channel();
    readback.map_async(wgpu::MapMode::Read, .., move |r| {
        let _ = tx.send(r);
    });
    if device.poll(wgpu::PollType::wait_indefinitely()).is_err() {
        return None;
    }
    rx.recv().ok()?.ok()?;

    let mapped = readback.get_mapped_range(..).ok()?;
    let mut pixels = Vec::with_capacity((unpadded * resolution) as usize);
    for row in 0..resolution as usize {
        let start = row * padded as usize;
        pixels.extend_from_slice(&mapped[start..start + unpadded as usize]);
    }
    drop(mapped);
    readback.unmap();
    Some(pixels)
}

