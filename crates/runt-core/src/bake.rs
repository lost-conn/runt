//! Baking a [`TextureSpec`] to GPU textures (DESIGN §7's baked path).
//!
//! > *Baked (baseline): rendered once to an RGBA8 texture at tier-scaled
//! > resolution at load time. This is a fragment pass, not compute — it works
//! > fully within WebGL2 limits (bake resolution capped at 2048² there).* — §7
//!
//! One spec produces **two** targets, from one octave loop:
//!
//! ```text
//!   TextureSpec ──► vs_bake (fullscreen triangle)
//!                     ├─ fs_albedo ─► RGBA8, ramp-mapped colour
//!                     └─ fs_normal ─► RGBA8, packed Voronoi-boundary normal
//! ```
//!
//! Two single-target passes rather than one MRT pass: two colour attachments
//! would also fit `downlevel_webgl2_defaults`, but a single attachment is the
//! shape every backend agrees on without thinking about it, and this is
//! load-time work the content cache mostly skips.
//!
//! ## Caching (DESIGN §6's invariant, applied one level down)
//!
//! Layered exactly like the mesh cache, and under the same rule: **the cache is
//! purely an optimization; deleting it must not change a pixel.**
//!
//! ```text
//!   TextureHandle (= content_key)
//!        ├─ in memory  → TextureRegistry: handle → GPU textures + bind group
//!        └─ persistent → CacheStore::load_texture: handle → raw RGBA8 bytes
//! ```
//!
//! A store entry is untrusted: it carries the `postcard` bytes of the spec it
//! was baked from and its resolution, and anything that does not match exactly
//! — wrong size, stale layout, key collision, hostile file — is discarded and
//! rebaked. `tests/texture_cache.rs` runs cold, warm and deleted-mid-run and
//! demands byte-identical pixels from all three.
//!
//! Reading pixels back off the GPU needs a blocking device poll, which is not
//! available on the web. Stores therefore opt in with
//! [`CacheStore::caches_textures`]; the default is `false`, so the web's
//! [`NoopCache`](crate::cache::NoopCache) path never tries.

use std::collections::HashMap;

use bytemuck::{Pod, Zeroable};
use serde::{Deserialize, Serialize};

use crate::cache::CacheStore;
use crate::texture::{TextureHandle, TextureSpec, MAX_OCTAVES, MAX_RAMP_STOPS};

/// The noise library, shared with any future live-eval variant.
pub const NOISE_SHADER: &str = include_str!("noise.wgsl");

/// The bake pass. Not standalone — see [`bake_shader_source`].
pub const BAKE_SHADER: &str = include_str!("bake.wgsl");

/// Both baked targets are RGBA8. Not sRGB: runt has no colour management, so a
/// baked albedo is in exactly the space `Material::base_color` is in, and the
/// normal target must be linear regardless.
pub const BAKE_FORMAT: wgpu::TextureFormat = wgpu::TextureFormat::Rgba8Unorm;

/// The bake shader, with the noise library prepended.
///
/// The dumbest possible include, matching
/// [`material::variant_source`](crate::material::variant_source)'s philosophy:
/// no `#include` grammar, no token scanning, just a concatenation — so both
/// files stay ordinary readable WGSL.
pub fn bake_shader_source() -> String {
    let mut out = String::with_capacity(NOISE_SHADER.len() + BAKE_SHADER.len() + 64);
    out.push_str("// generated by runt_core::bake::bake_shader_source\n");
    out.push_str(NOISE_SHADER);
    out.push('\n');
    out.push_str(BAKE_SHADER);
    out
}

