/// `@group(0)` of the bake pass. Field order is restated in `bake.wgsl`.
///
/// The octave table is *planned on the CPU* ([`TextureSpec::octave_plan`]), so
/// the shader contains no `pow`, no rounding rule and no lattice-period
/// arithmetic it could get subtly different from the Rust twin.
#[repr(C)]
#[derive(Clone, Copy, Debug, Pod, Zeroable)]
pub struct BakeUniform {
    /// lattice, cell return type, fractal, octave count.
    pub mode: [u32; 4],
    /// normal mode, ramp stop count, unused, unused.
    pub counts: [u32; 4],
    /// jitter, contrast, brightness, ridged weighted strength.
    pub shape: [f32; 4],
    /// edge width, normal strength, analytic texel delta, unused.
    pub normal: [f32; 4],
    /// seed offset xyz, unused.
    pub seed: [f32; 4],
    /// Per octave: span, frequency, amplitude, LOD weight.
    pub octaves: [[f32; 4]; MAX_OCTAVES],
    /// Per stop: rgb, offset.
    pub ramp: [[f32; 4]; MAX_RAMP_STOPS],
}

impl BakeUniform {
    /// Flatten a spec into the uniform the shader reads.
    pub fn from_spec(spec: &TextureSpec) -> BakeUniform {
        let plan = spec.octave_plan();
        let normal = spec.normal;
        let offset = crate::noise::seed_offset_3d(spec.seed_offset);

        let mut octaves = [[0.0f32; 4]; MAX_OCTAVES];
        for (slot, o) in octaves.iter_mut().zip(&plan) {
            *slot = [o.span, o.freq, o.amplitude, o.weight];
        }

        let mut ramp = [[0.0f32; 4]; MAX_RAMP_STOPS];
        let stops = spec.ramp.len().min(MAX_RAMP_STOPS);
        for (slot, (at, color)) in ramp.iter_mut().zip(&spec.ramp) {
            *slot = [color.x, color.y, color.z, *at];
        }

        // The step the boundary normal differentiates over: a fixed fraction of
        // the tile, so the normal map does not flatten out on a low tier (see
        // `texture::NORMAL_REFERENCE_TEXELS`).
        let base_span = plan.first().map(|o| o.span).unwrap_or(1.0);
        let delta = base_span / crate::texture::NORMAL_REFERENCE_TEXELS;

        BakeUniform {
            mode: [
                match spec.noise.lattice() {
                    crate::noise::Lattice::Cubic => 0,
                    crate::noise::Lattice::Fcc => 1,
                },
                spec.noise.return_type().code(),
                spec.fractal.code(),
                plan.len() as u32,
            ],
            counts: [
                normal.map(|n| n.mode.code()).unwrap_or(0),
                stops as u32,
                0,
                0,
            ],
            shape: [
                spec.noise.jitter(),
                spec.contrast,
                spec.brightness,
                spec.weighted_strength,
            ],
            normal: [
                normal.map(|n| n.edge_width).unwrap_or(0.25),
                normal.map(|n| n.strength).unwrap_or(1.0),
                delta,
                0.0,
            ],
            seed: [offset.x, offset.y, offset.z, 0.0],
            octaves,
            ramp,
        }
    }
}

